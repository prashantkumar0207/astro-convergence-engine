def gate_d_isolation():
    import ast
    import hashlib
    import inspect

    this_module = sys.modules[__name__]
    own_source = inspect.getsource(this_module)
    tree = ast.parse(own_source)
    forbidden_names = ("varga_d4", "varga_registry", "CyclicVargaRule")
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom):
            module_name = node.module or ""
            imported_names = [alias.name for alias in node.names]
            if "varga_d4" in module_name or "varga_registry" in module_name:
                fail(f"certify_d4.py imports {module_name} - must remain standalone, "
                     f"never touch the registry")
            if "CyclicVargaRule" in imported_names:
                fail("certify_d4.py imports CyclicVargaRule - must remain isolated to "
                     "SegmentVargaRule only, per the owner's explicit isolation instruction")
        elif isinstance(node, ast.Import):
            for alias in node.names:
                if any(name in alias.name for name in forbidden_names):
                    fail(f"certify_d4.py imports {alias.name} - forbidden by isolation")

    if (ROOT / "engine" / "astrology" / "varga_d4.py").exists():
        fail("engine/astrology/varga_d4.py already exists - certification design/"
             "execution does not authorize production implementation")

    # Mechanical proof, not merely a design commitment: the shared framework
    # file this certifier's own CyclicVargaRule-avoidance claim depends on is
    # byte-for-byte unchanged from its currently-committed content.
    varga_rules_path = ROOT / "engine" / "astrology" / "varga_rules.py"
    current_hash = hashlib.sha256(varga_rules_path.read_bytes()).hexdigest()
    if current_hash != BASELINE_VARGA_RULES_SHA256:
        fail(f"engine/astrology/varga_rules.py content changed: {current_hash} != "
             f"baseline {BASELINE_VARGA_RULES_SHA256} - the shared CyclicVargaRule/"
             f"classifier architecture must not be modified to support D4")

    return {
        "certifier_never_imports_varga_registry_or_varga_d4": True,
        "certifier_never_imports_cyclicvargarule": True,
        "engine_astrology_varga_d4_absent": True,
        "content_sha256_matches_pinned": rule_content_sha256(D4_CHATURTHAMSA) == CERTIFIED_D4_CONTENT_SHA256,
        "varga_rules_py_sha256": current_hash,
        "varga_rules_py_unchanged_from_baseline": True,
    }


