_KENDRA_OFFSETS = (0, 3, 6, 9)

D4_CHATURTHAMSA = SegmentVargaRule(
    segments=tuple(
        tuple((_WIDTH, (source + offset) % 12) for offset in _KENDRA_OFFSETS)
        for source in range(12)
    ),
    division=4,
)

