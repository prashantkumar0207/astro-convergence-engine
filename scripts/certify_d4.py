def gate_f_boundary_cases():
    import math
    cases = 0
    mismatches = 0
    for sign in range(12):
        for k in range(1, 4):
            exact_boundary = k * _WIDTH
            cases += 1
            result = classify(sign * 30.0 + exact_boundary, D4_CHATURTHAMSA)
            expected_sign, expected_division = _independent_d4_sign(sign, exact_boundary)
            if (result.d_sign, result.division_index) != (expected_sign, expected_division):
                mismatches += 1
    for sign in range(12):
        # Mirrors D24/D40/D45's own corrected boundary-probe construction
        # (ADR-0083 gate F): computed at the target magnitude directly, not
        # via an addition that can round away the intended epsilon.
        near_end = classify(math.nextafter((sign + 1) * 30.0, -math.inf), D4_CHATURTHAMSA)
        start = classify(sign * 30.0, D4_CHATURTHAMSA)
        cases += 2
        if near_end.division_index != 3:
            mismatches += 1
        if start.division_index != 0:
            mismatches += 1
    if mismatches:
        fail(f"boundary case failures: {mismatches}/{cases}")
    return {"cases": cases, "mismatches": 0,
            "convention": "engine-wide 1e-10 tolerance-promoted boundary convention "
                           "(longitude_utils.py), unmodified; no D4-specific exception - "
                           "cell width 30/4=7.5deg is exactly representable in IEEE-754 "
                           "double precision (ADR-0090 section 3), zero floor-"
                           "classification effect, identical clean result to D24's/D40's own"}


def gate_g_protected_holdout():
    mismatches = 0
    count = 0
    step = 0.0137
    longitude = 0.0
    while longitude < 360.0:
        source = int(longitude // 30.0)
        degree = longitude - source * 30.0
        result = classify(longitude, D4_CHATURTHAMSA)
        expected_sign, expected_division = _independent_d4_sign(source, degree)
        if (result.d_sign, result.division_index) != (expected_sign, expected_division):
            mismatches += 1
        count += 1
        longitude += step
    if mismatches:
        fail(f"protected holdout mismatches: {mismatches}")
    return {"points": count, "mismatches": 0,
            "methodology": "prime-step deterministic sampling, independent of gate B/F "
                            "points, never used to tune the frozen rule"}


def gate_h_negative_controls():
    from dataclasses import replace

    controls = []

    original_segments = D4_CHATURTHAMSA.segments
    mutated_first = ((_WIDTH, 5),) + original_segments[0][1:]
    mutated = replace(
        D4_CHATURTHAMSA,
        segments=(mutated_first,) + original_segments[1:],
    )
    detected = mutated.segments[0][0] != D4_CHATURTHAMSA.segments[0][0]
    controls.append({"control": "segments[0][0] target mutated 0->5 (wrong value)", "detected": detected})
    if not detected:
        fail("negative control 1 did not detect the planted mutation")

    test_longitude = 30.0 + 10.0  # within Taurus (source=1), division 1
    mutated_result = classify(test_longitude, mutated)
    original_result = classify(test_longitude, D4_CHATURTHAMSA)
    # The mutation only touches source sign 0 (Aries); probe a Taurus point
    # instead to independently confirm mutation on ONE source sign does not
    # silently affect classification of a DIFFERENT, unmutated source sign -
    # then probe Aries itself for the direct detection.
    aries_probe = classify(3.7, mutated)
    aries_original = classify(3.7, D4_CHATURTHAMSA)
    detected_2 = aries_probe.d_sign != aries_original.d_sign
    controls.append({"control": "Aries (mutated source) division 0 target flip detected", "detected": detected_2})
    if not detected_2:
        fail("negative control 2 did not detect the planted mutation")
    unaffected = mutated_result.d_sign == original_result.d_sign and mutated_result.division_index == original_result.division_index
    controls.append({"control": "Taurus (unmutated source) unaffected by Aries-only mutation", "detected": unaffected})
    if not unaffected:
        fail("negative control 2b: mutation to one source sign leaked into another - "
             "the classifier or rule object is not isolating segments per source sign correctly")

    original_hash = rule_content_sha256(D4_CHATURTHAMSA)
    mutated_hash = rule_content_sha256(mutated)
    detected_3 = mutated_hash != original_hash
    controls.append({"control": "content hash changes on mutation", "detected": detected_3})
    if not detected_3:
        fail("negative control 3 did not detect the planted mutation")

    restored_hash = rule_content_sha256(D4_CHATURTHAMSA)
    if restored_hash != original_hash:
        fail("D4_CHATURTHAMSA itself was mutated - this must never happen (dataclass is frozen)")

    return {"controls": controls, "all_detected": True, "original_object_unmutated": True}


