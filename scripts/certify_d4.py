#: Frozen exactly as ADR-0090 section 3 states it: division `l` (0-3) of
#: 0-based source sign `s` maps to target sign `(s + 3*l) mod 12` - the
#: source sign itself, then its 4th, 7th, and 10th houses counted from it
#: (the four kendras). Uniform across all twelve source signs. A standalone
#: object - never registered via
#: engine.astrology.varga_registry.register_varga_rule.
