def _independent_d4_sign(source_sign: int, degree_in_sign: float):
    """Independently coded reference (ADR-0090 section 3), not imported from
    the rule under test - only the classical kendra-counting description is
    used, re-derived from first principles. Applies the engine's own
    documented boundary-promotion rule on its own terms (re-derived, not
    imported), so this checks whether classify() correctly IMPLEMENTS the
    documented convention, not a self-comparison."""

    segment_index = int((degree_in_sign + 1e-10) / _WIDTH)
    if segment_index > 3:
        segment_index = 3
    return (source_sign + _KENDRA_OFFSETS[segment_index]) % 12, segment_index


def gate_a_table_integrity():
    if D4_CHATURTHAMSA.division != 4:
        fail("division != 4")
    for source in range(12):
        segments = D4_CHATURTHAMSA.segments[source]
        if len(segments) != 4:
            fail(f"sign {source}: expected 4 segments")
        for division, (width, target) in enumerate(segments):
            if width != _WIDTH:
                fail(f"sign {source} division {division}: width {width}")
            expected_target = (source + _KENDRA_OFFSETS[division]) % 12
            if target != expected_target:
                fail(f"sign {source} division {division}: target {target}, expected {expected_target}")
    return {
        "cells": 48,
        "mismatches": 0,
        "content_sha256": rule_content_sha256(D4_CHATURTHAMSA),
        "disclosure": "division l (0-3) of source sign s maps to target (s + 3*l) mod 12 - "
                       "the source sign itself, then its 4th, 7th, and 10th houses (the four "
                       "kendras from the source sign), uniform for all twelve source signs - "
                       "Parashara/BPHS, DP-032 section A (ADR-0090 section 3)",
    }


def gate_b_dense_sweep():
    mismatches = 0
    points = 51429
    step = 360.0 / points
    for i in range(points):
        longitude = i * step
        result = classify(longitude, D4_CHATURTHAMSA)
        source = int(longitude // 30.0)
        degree = longitude - source * 30.0
        expected_sign, expected_division = _independent_d4_sign(source, degree)
        if (result.d_sign, result.division_index) != (expected_sign, expected_division):
            mismatches += 1
    if mismatches:
        fail(f"dense sweep mismatches: {mismatches}")
    return {"points": points, "mismatches": 0}


