def gate_f_boundary_cases():
    import math
    cases = 0
    mismatches = 0
    width = 30.0 / 40.0
    for sign in range(12):
        for k in range(1, 40):
            exact_boundary = k * width
            cases += 1
            result = classify(sign * 30.0 + exact_boundary, D40_KHAVEDAMSA)
            expected_sign, expected_division = _independent_d40_sign(sign, exact_boundary)
            if (result.d_sign, result.division_index) != (expected_sign, expected_division):
                mismatches += 1
    for sign in range(12):
        # Mirrors D24/D45's own corrected boundary-probe construction
        # (ADR-0083 gate F): computed at the target magnitude directly, not
        # via an addition that can round away the intended epsilon.
        near_end = classify(math.nextafter((sign + 1) * 30.0, -math.inf), D40_KHAVEDAMSA)
        start = classify(sign * 30.0, D40_KHAVEDAMSA)
        cases += 2
        if near_end.division_index != 39:
            mismatches += 1
        if start.division_index != 0:
            mismatches += 1
    if mismatches:
        fail(f"boundary case failures: {mismatches}/{cases}")
    return {"cases": cases, "mismatches": 0,
            "convention": "engine-wide 1e-10 tolerance-promoted boundary convention "
                           "(longitude_utils.py), unmodified; no D40-specific exception - "
                           "cell width 30/40=0.75deg is exactly representable in IEEE-754 "
                           "double precision (ADR-0087 section 3), zero floor-"
                           "classification effect, identical clean result to D24's own"}


def gate_g_protected_holdout():
    mismatches = 0
    count = 0
    step = 0.0137
    longitude = 0.0
    while longitude < 360.0:
        source = int(longitude // 30.0)
        degree = longitude - source * 30.0
        result = classify(longitude, D40_KHAVEDAMSA)
        expected_sign, expected_division = _independent_d40_sign(source, degree)
        if (result.d_sign, result.division_index) != (expected_sign, expected_division):
            mismatches += 1
        count += 1
        longitude += step
    if mismatches:
        fail(f"protected holdout mismatches: {mismatches}")
    return {"points": count, "mismatches": 0,
            "methodology": "prime-step deterministic sampling, independent of gate B/F "
                            "points, never used to tune the frozen rule"}


def gate_h_negative_controls():
    from dataclasses import replace

    controls = []

    mutated = replace(D40_KHAVEDAMSA, start_sign=(1,) + D40_KHAVEDAMSA.start_sign[1:])
    detected = mutated.start_sign[0] != D40_KHAVEDAMSA.start_sign[0]
    controls.append({"control": "start_sign[0] mutated Aries->wrong value", "detected": detected})
    if not detected:
        fail("negative control 1 did not detect the planted mutation")

    mutated_dir = replace(
        D40_KHAVEDAMSA,
        direction=D40_KHAVEDAMSA.direction[:1] + (-1,) + D40_KHAVEDAMSA.direction[2:],
    )
    test_longitude = 30.0 + 7.0  # within Taurus (even, source=1), segment index != multiple of 12
    mutated_result = classify(test_longitude, mutated_dir)
    original_result = classify(test_longitude, D40_KHAVEDAMSA)
    detected_2 = mutated_result.d_sign != original_result.d_sign
    controls.append({"control": "direction[1] mutated +1->-1", "detected": detected_2})
    if not detected_2:
        fail("negative control 2 did not detect the planted mutation")

    original_hash = rule_content_sha256(D40_KHAVEDAMSA)
    mutated_hash = rule_content_sha256(mutated)
    detected_3 = mutated_hash != original_hash
    controls.append({"control": "content hash changes on mutation", "detected": detected_3})
    if not detected_3:
        fail("negative control 3 did not detect the planted mutation")

    restored_hash = rule_content_sha256(D40_KHAVEDAMSA)
    if restored_hash != original_hash:
        fail("D40_KHAVEDAMSA itself was mutated - this must never happen (dataclass is frozen)")

    return {"controls": controls, "all_detected": True, "original_object_unmutated": True}


