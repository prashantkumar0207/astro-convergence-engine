def gate_d_isolation():
    import ast
    import inspect

    this_module = sys.modules[__name__]
    own_source = inspect.getsource(this_module)
    tree = ast.parse(own_source)
    for node in ast.walk(tree):
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            module_name = getattr(node, "module", None) or (
                node.names[0].name if isinstance(node, ast.Import) else None
            )
            if module_name and (
                "varga_d40" in module_name or "varga_registry" in module_name
            ):
                fail(f"certify_d40.py imports {module_name} - must remain standalone, "
                     f"never touch the registry")

    if not (ROOT / "engine" / "astrology" / "varga_d40.py").exists():
        registered = True
    else:
        fail("engine/astrology/varga_d40.py already exists - certification design/"
             "execution does not authorize production implementation")
    return {
        "certifier_never_imports_varga_registry_or_varga_d40": True,
        "engine_astrology_varga_d40_absent": registered,
        "content_sha256_matches_pinned": rule_content_sha256(D40_KHAVEDAMSA) == CERTIFIED_D40_CONTENT_SHA256,
    }


