#: Frozen exactly as ADR-0087 section 3 states it: odd source signs
#: (0-based Aries=0, Gemini=2, Leo=4, Libra=6, Sagittarius=8, Aquarius=10)
#: start from Aries (index 0); even source signs (Taurus=1, Cancer=3,
#: Virgo=5, Scorpio=7, Capricorn=9, Pisces=11) start from Libra (index 6);
#: forward counting (direction +1) for all twelve. A standalone object -
#: never registered via engine.astrology.varga_registry.register_varga_rule.
_ODD_SOURCE_SIGNS = frozenset({0, 2, 4, 6, 8, 10})
_ARIES, _LIBRA = 0, 6

D40_KHAVEDAMSA = CyclicVargaRule(
    divisions=40,
    start_sign=tuple(_ARIES if s in _ODD_SOURCE_SIGNS else _LIBRA for s in range(12)),
    direction=(1,) * 12,
)

#: Content fingerprint of the frozen rule above, pinned as a literal
#: hardcoded value from a prior intentional run (NOT computed from itself,
#: which would trivially always match and defeat the point of a pin -
#: mirrors scripts/certify_d24.py's own CERTIFIED_D24_CONTENT_SHA256
#: pattern exactly). Computed once via rule_content_sha256(D40_KHAVEDAMSA)
#: and verified independently before being pinned here.
CERTIFIED_D40_CONTENT_SHA256 = (
    "056e3e8af182568e9e2eaa5a1f54d86c40f7d97a53ece610f1e3105eb7a41006"
)


def fail(message):
    print("D40 CERTIFICATION FAIL:", message)
    sys.exit(3)


def _independent_d40_sign(source_sign: int, degree_in_sign: float):
    """Independently coded reference (ADR-0087 section 3), not imported from
    the rule under test - only the classical odd/even description is used,
    re-derived from first principles. Applies the engine's own documented
    boundary-promotion rule on its own terms (re-derived, not imported), so
    this checks whether classify() correctly IMPLEMENTS the documented
    convention, not a self-comparison."""

    segment_width = 30.0 / 40.0
    segment_index = int((degree_in_sign + 1e-10) / segment_width)
    if segment_index > 39:
        segment_index = 39
    start = _ARIES if source_sign in _ODD_SOURCE_SIGNS else _LIBRA
    return (start + segment_index) % 12, segment_index


def gate_a_table_integrity():
    if D40_KHAVEDAMSA.divisions != 40:
        fail("divisions != 40")
    for source in range(12):
        expected = _ARIES if source in _ODD_SOURCE_SIGNS else _LIBRA
        if D40_KHAVEDAMSA.start_sign[source] != expected:
            fail(f"sign {source}: start {D40_KHAVEDAMSA.start_sign[source]}, expected {expected}")
        if D40_KHAVEDAMSA.direction[source] != 1:
            fail(f"sign {source}: direction")
    return {
        "cells": 12,
        "mismatches": 0,
        "content_sha256": rule_content_sha256(D40_KHAVEDAMSA),
        "disclosure": "odd source signs (0-based 0,2,4,6,8,10) start Aries (index 0); "
                       "even source signs (1,3,5,7,9,11) start Libra (index 6); "
                       "forward counting for all twelve - Parashara/BPHS, DP-031 section J "
                       "(ADR-0087 section 3)",
    }


def gate_b_dense_sweep():
    mismatches = 0
    points = 51429
    step = 360.0 / points
    for i in range(points):
        longitude = i * step
        result = classify(longitude, D40_KHAVEDAMSA)
        source = int(longitude // 30.0)
        degree = longitude - source * 30.0
        expected_sign, expected_division = _independent_d40_sign(source, degree)
        if (result.d_sign, result.division_index) != (expected_sign, expected_division):
            mismatches += 1
    if mismatches:
        fail(f"dense sweep mismatches: {mismatches}")
    return {"points": points, "mismatches": 0}


