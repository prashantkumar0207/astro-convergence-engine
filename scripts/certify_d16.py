def gate_f_boundary_cases():
    import math
    cases = 0
    mismatches = 0
    width = 30.0 / 16.0
    for sign in range(12):
        for k in range(1, 16):
            exact_boundary = k * width
            cases += 1
            result = classify(sign * 30.0 + exact_boundary, D16_SHODASAMSA)
            expected_sign, expected_division = validate_d16_holdout.reference_d16(
                sign * 30.0 + exact_boundary
            )
            if (result.d_sign, result.division_index) != (expected_sign, expected_division):
                mismatches += 1
    for sign in range(12):
        # Mirrors D24/D40/D45's own corrected boundary-probe construction
        # (ADR-0083 gate F): computed at the target magnitude directly, not
        # via an addition that can round away the intended epsilon.
        near_end = classify(math.nextafter((sign + 1) * 30.0, -math.inf), D16_SHODASAMSA)
        start = classify(sign * 30.0, D16_SHODASAMSA)
        cases += 2
        if near_end.division_index != 15:
            mismatches += 1
        if start.division_index != 0:
            mismatches += 1
    if mismatches:
        fail(f"boundary case failures: {mismatches}/{cases}")
    return {"cases": cases, "mismatches": 0,
            "verified_against": "validate_d16_holdout.reference_d16() (imported directly)",
            "convention": "engine-wide 1e-10 tolerance-promoted boundary convention "
                           "(longitude_utils.py), unmodified; no D16-specific exception - "
                           "cell width 30/16=1.875deg is exactly representable in IEEE-754 "
                           "double precision (ADR-0089 section 3), zero floor-"
                           "classification effect, identical clean result to D24's/D40's own"}


