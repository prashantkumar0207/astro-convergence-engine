#: Frozen exactly as ADR-0089 section 3 states it: movable source signs
#: (0-based Aries=0, Cancer=3, Libra=6, Capricorn=9) start from Aries
#: (index 0); fixed source signs (Taurus=1, Leo=4, Scorpio=7, Aquarius=10)
#: start from Leo (index 4); dual source signs (Gemini=2, Virgo=5,
#: Sagittarius=8, Pisces=11) start from Sagittarius (index 8); forward
#: counting (direction +1) for all twelve. A standalone object - never
#: registered via engine.astrology.varga_registry.register_varga_rule.
_MOVABLE_SOURCE_SIGNS = frozenset({0, 3, 6, 9})
_FIXED_SOURCE_SIGNS = frozenset({1, 4, 7, 10})
_ARIES, _LEO, _SAGITTARIUS = 0, 4, 8


def _start_for_source(source_sign: int) -> int:
    if source_sign in _MOVABLE_SOURCE_SIGNS:
        return _ARIES
    if source_sign in _FIXED_SOURCE_SIGNS:
        return _LEO
    return _SAGITTARIUS


D16_SHODASAMSA = CyclicVargaRule(
    divisions=16,
    start_sign=tuple(_start_for_source(s) for s in range(12)),
    direction=(1,) * 12,
)

