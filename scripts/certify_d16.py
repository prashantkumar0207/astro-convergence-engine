def _independent_d16_sign(source_sign: int, degree_in_sign: float):
    """Independently coded reference (ADR-0089 section 3), not imported from
    the rule under test - only the classical movable/fixed/dual description
    is used, re-derived from first principles. Applies the engine's own
    documented boundary-promotion rule on its own terms (re-derived, not
    imported), so this checks whether classify() correctly IMPLEMENTS the
    documented convention, not a self-comparison."""

    segment_width = 30.0 / 16.0
    segment_index = int((degree_in_sign + 1e-10) / segment_width)
    if segment_index > 15:
        segment_index = 15
    start = _start_for_source(source_sign)
    return (start + segment_index) % 12, segment_index


def gate_a_table_integrity():
    if D16_SHODASAMSA.divisions != 16:
        fail("divisions != 16")
    for source in range(12):
        expected = _start_for_source(source)
        if D16_SHODASAMSA.start_sign[source] != expected:
            fail(f"sign {source}: start {D16_SHODASAMSA.start_sign[source]}, expected {expected}")
        if D16_SHODASAMSA.direction[source] != 1:
            fail(f"sign {source}: direction")
    return {
        "cells": 12,
        "mismatches": 0,
        "content_sha256": rule_content_sha256(D16_SHODASAMSA),
        "disclosure": "movable source signs (0-based 0,3,6,9) start Aries (index 0); "
                       "fixed source signs (1,4,7,10) start Leo (index 4); "
                       "dual source signs (2,5,8,11) start Sagittarius (index 8); "
                       "forward counting for all twelve - Parashara/BPHS, DP-032 section B "
                       "(ADR-0089 section 3)",
    }


def gate_b_dense_sweep():
    mismatches = 0
    points = 51429
    step = 360.0 / points
    for i in range(points):
        longitude = i * step
        result = classify(longitude, D16_SHODASAMSA)
        source = int(longitude // 30.0)
        degree = longitude - source * 30.0
        expected_sign, expected_division = _independent_d16_sign(source, degree)
        if (result.d_sign, result.division_index) != (expected_sign, expected_division):
            mismatches += 1
    if mismatches:
        fail(f"dense sweep mismatches: {mismatches}")
    return {"points": points, "mismatches": 0}


