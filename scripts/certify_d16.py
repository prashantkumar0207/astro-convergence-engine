def gate_h_negative_controls():
    from dataclasses import replace

    controls = []

    mutated = replace(D16_SHODASAMSA, start_sign=(1,) + D16_SHODASAMSA.start_sign[1:])
    detected = mutated.start_sign[0] != D16_SHODASAMSA.start_sign[0]
    controls.append({"control": "start_sign[0] mutated Aries->wrong value", "detected": detected})
    if not detected:
        fail("negative control 1 did not detect the planted mutation")

    mutated_dir = replace(
        D16_SHODASAMSA,
        direction=D16_SHODASAMSA.direction[:1] + (-1,) + D16_SHODASAMSA.direction[2:],
    )
    test_longitude = 30.0 + 7.0  # within Taurus (fixed, source=1), segment index != multiple of 12
    mutated_result = classify(test_longitude, mutated_dir)
    original_result = classify(test_longitude, D16_SHODASAMSA)
    detected_2 = mutated_result.d_sign != original_result.d_sign
    controls.append({"control": "direction[1] mutated +1->-1", "detected": detected_2})
    if not detected_2:
        fail("negative control 2 did not detect the planted mutation")

    original_hash = rule_content_sha256(D16_SHODASAMSA)
    mutated_hash = rule_content_sha256(mutated)
    detected_3 = mutated_hash != original_hash
    controls.append({"control": "content hash changes on mutation", "detected": detected_3})
    if not detected_3:
        fail("negative control 3 did not detect the planted mutation")

    # DP-032 addendum, Finding 2: proves the REAL enforcement path (the exact
    # function gate D calls to decide pass/fail), not a separately simulated
    # comparison. Before this addendum, a hash mismatch was reported but
    # never enforced - this control would have been meaningless without the
    # gate D fix above.
    hash_check_rejects_mutation = not _content_hash_matches(mutated)
    hash_check_accepts_original = _content_hash_matches(D16_SHODASAMSA)
    detected_4 = hash_check_rejects_mutation and hash_check_accepts_original
    controls.append({"control": "gate D's own _content_hash_matches() helper rejects the "
                                 "mutated rule and accepts the original", "detected": detected_4})
    if not detected_4:
        fail("negative control 4 did not detect the planted mutation via the real "
             "enforcement helper")

    # DP-032 addendum, Finding 1: proves the NEW independent-reference check
    # (validate_d16_holdout.reference_d16(), imported directly) actually
    # catches a classical-content mutation - the exact failure mode an
    # adversarial audit found gates A/B/F/G previously missed, because they
    # compared against an in-file helper sharing code with the rule's own
    # construction. Swaps which start sign the fixed/dual triplicities use -
    # a real content error, not a structural one.
    content_mutated = replace(
        D16_SHODASAMSA,
        start_sign=tuple(
            _SAGITTARIUS if D16_SHODASAMSA.start_sign[s] == _LEO
            else _LEO if D16_SHODASAMSA.start_sign[s] == _SAGITTARIUS
            else D16_SHODASAMSA.start_sign[s]
            for s in range(12)
        ),
    )
    probe_longitude = 30.0 + 7.3  # Taurus (fixed, source=1): start Leo -> mutated to Sagittarius
    probe_result = classify(probe_longitude, content_mutated)
    probe_expected_sign, probe_expected_division = validate_d16_holdout.reference_d16(probe_longitude)
    detected_5 = (probe_result.d_sign, probe_result.division_index) != (probe_expected_sign, probe_expected_division)
    controls.append({"control": "fixed/dual start-sign swap (the exact audit-demonstrated "
                                 "content mutation) now disagrees with the independent "
                                 "reference_d16()", "detected": detected_5})
    if not detected_5:
        fail("negative control 5 did not detect the audit-demonstrated content mutation "
             "via the new independent-reference check")

    restored_hash = rule_content_sha256(D16_SHODASAMSA)
    if restored_hash != original_hash:
        fail("D16_SHODASAMSA itself was mutated - this must never happen (dataclass is frozen)")

    return {"controls": controls, "all_detected": True, "original_object_unmutated": True}


